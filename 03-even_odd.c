#include <stdio.h>
int main()
{ 
    int num1 =16;
    int num2 =7;

    if (num1 % 2 == 0) {
        printf("%d is Even number\n", num1);
    } else {
        printf("%d is Odd number\n", num1);
    }

    if (num2 % 2 == 0) {
        printf("%d is Even number\n", num2);
    } else {
        printf("%d is Odd number\n", num2);
    }

    return 0;
    
}